use super::{
    data::Data,
    replaces::{count_checksum, Replace},
};
use std::collections::BTreeMap;
pub fn generate(data: &Data, replaces: &[Replace]) -> crate::common::Result<String> {
    let mut parent = 0usize;
    let mut init = Vec::new();
    let mut colored_count = 0usize;
    let mut colors_count = 0usize;
    let mut total = 0usize;
    for (index, e) in data.list.iter().enumerate() {
        if e.id.len() >= 64 {
            return Err(super::data_read::bad("Too large id."));
        }
        total += e.id.len();
        if parent + 1 >= 4096 {
            return Err(super::data_read::bad("Too many entries."));
        }
        init.push((
            if e.colored { parent + 1 } else { 0 },
            e.id.len(),
            e.postfixed,
            e.variated,
        ));
        if colored_count > 0 && (e.variated || !e.colored) {
            if colors_count == 0 {
                colors_count = colored_count;
            } else if colors_count != colored_count {
                return Err(super::data_read::bad(
                    "different colored emoji count exist.",
                ));
            }
            colored_count = 0;
        }
        if e.variated {
            parent = index;
        } else if e.colored {
            if parent == 0 {
                return Err(super::data_read::bad("wrong order of colored items."));
            }
            colored_count += 1;
        } else {
            parent = 0;
        }
    }
    if total >= 65535 {
        return Err(super::data_read::bad("Too many IdData elements."));
    }

    let mut out = String::from(
        "// Generated by tg-codegen. Do not edit.\nuse tg_ui::emoji::{Emoji, Replacement};\n",
    );
    out+=&format!("pub static EMOJI_INIT: &[(usize,usize,bool,bool)] = &{init:?};\npub const COLORS_COUNT: usize = {colors_count};\n");
    out += "pub static EMOJI: &[Emoji] = &[\n";
    for e in &data.list {
        out += &format!(
            "Emoji {{ id: &{:?}, postfixed: {}, variated: {}, colored: {} }},\n",
            e.id, e.postfixed, e.variated, e.colored
        );
    }
    out += "];\n";
    out += &format!(
        "pub static POSTFIX_REQUIRED: &[usize] = &{:?};\npub static CATEGORIES: &[&[usize]] = &[",
        data.postfix_required.iter().copied().collect::<Vec<_>>()
    );
    for c in &data.categories {
        out += &format!("&{c:?},");
    }
    out += "];\n";
    out += "pub static ID_MAP: &[(&[u16], usize)] = &[";
    for (id, index) in data.map.iter().rev() {
        out += &format!("(&{id:?}, {index}),");
    }
    out += "];\n";
    out += "pub static EMOTICONS: &[(&str, usize)] = &[";
    for (s, index) in data.replaces.iter().rev() {
        out += &format!("({s:?}, {index}),");
    }
    out += "];\n";
    out += "pub static REPLACEMENTS: &[Replacement] = &[\n";
    let mut by_char = BTreeMap::<u16, Vec<usize>>::new();
    let mut binary = Vec::<u16>::new();
    let mut lengths = Vec::<usize>::new();
    let mut init = Vec::new();
    for (i, r) in replaces.iter().enumerate() {
        out += &format!(
            "Replacement {{ id: &{:?}, replacement: {:?}, words: &[{}], checksum: {} }},\n",
            r.id,
            r.replacement,
            r.words
                .iter()
                .map(|s| format!("{s:?}"))
                .collect::<Vec<_>>()
                .join(","),
            count_checksum(&r.replacement)
        );
        binary.extend(&r.id);
        binary.extend(r.replacement.encode_utf16());
        for w in &r.words {
            let units: Vec<_> = w.encode_utf16().collect();
            let indices = by_char.entry(units[0]).or_default();
            if indices.last() != Some(&i) {
                indices.push(i);
            }
            lengths.push(units.len());
            binary.extend(units);
        }
        init.push((
            r.id.len(),
            r.replacement.encode_utf16().count(),
            r.words.len(),
        ));
    }
    out += "];\n";
    out+=&format!("pub static REPLACEMENT_DATA: &[u16] = &{binary:?};\npub static WORD_LENGTHS: &[usize] = &{lengths:?};\npub static REPLACEMENT_INIT: &[(usize,usize,usize)] = &{init:?};\n");
    out += "pub static BY_CHAR: &[(u16, &[usize])] = &[";
    for (ch, indices) in by_char {
        out += &format!("({ch}, &{indices:?}),");
    }
    out += "];\n";
    Ok(out)
}
