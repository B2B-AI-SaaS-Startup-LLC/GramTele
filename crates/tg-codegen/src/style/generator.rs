use super::{module::Module, structure_types::*};
use crate::common::{Error, Result};
use std::collections::BTreeMap;
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct PaletteColor {
    pub name: String,
    pub rgba: [u8; 4],
    pub fallback: i32,
    pub index: usize,
}
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Palette {
    pub colors: Vec<PaletteColor>,
    pub checksum_input: String,
    pub checksum: i32,
}
pub fn palette(module: &Module) -> Result<Palette> {
    let mut colors = vec![
        PaletteColor {
            name: "transparent".into(),
            rgba: [255, 255, 255, 0],
            fallback: -1,
            index: 0,
        },
        PaletteColor {
            name: "white".into(),
            rgba: [255, 255, 255, 255],
            fallback: -1,
            index: 1,
        },
    ];
    let mut input = String::from("&transparent:{ 255, 255, 255, 0 }&white:{ 255, 255, 255, 255 }");
    let mut indices = BTreeMap::new();
    for v in &module.variables {
        let Data::Color { rgba, fallback } = &v.value.data else {
            return Err(Error::new(
                &module.path,
                0,
                802,
                "type mismatch: palette color",
            ));
        };
        let index = colors.len();
        indices.insert(v.name.clone(), index);
        let fallback = if v.value.copy_of.is_empty() {
            fallback
        } else {
            &v.value.copy_of
        };
        let fallback = indices.get(fallback).map_or(-1, |&n| n as i32);
        input += &format!(
            "&{}:{{ {}, {}, {}, {} }}",
            v.name, rgba[0], rgba[1], rgba[2], rgba[3]
        );
        colors.push(PaletteColor {
            name: v.name.clone(),
            rgba: *rgba,
            fallback,
            index,
        });
    }
    let checksum = tg_base::crc32hash::crc32(input.as_bytes());
    Ok(Palette {
        colors,
        checksum_input: input,
        checksum,
    })
}
pub fn module_name(m: &Module) -> String {
    if m.palette {
        "palette".into()
    } else {
        format!(
            "style_{}",
            std::path::Path::new(&m.path)
                .file_stem()
                .unwrap()
                .to_string_lossy()
        )
    }
}
pub fn ident(s: &str) -> String {
    format!("r#{s}")
}
fn ty(t: &Type) -> String {
    match t {
        Type::Int | Type::Pixels => "i32".into(),
        Type::Bool => "bool".into(),
        Type::Double => "f64".into(),
        Type::String => "String".into(),
        Type::Struct(n) => ident(n),
        _ => format!(
            "tg_ui::style::{}",
            match t {
                Type::Color => "Color",
                Type::Point => "Point",
                Type::Size => "Size",
                Type::Align => "Align",
                Type::Margins => "Margins",
                Type::Font => "Font",
                Type::Icon => "Icon",
                _ => unreachable!(),
            }
        ),
    }
}
pub fn generate(module: &Module) -> Result<String> {
    let mut out = String::from("// Generated by tg-codegen. Do not edit.\n");
    for m in &module.includes {
        out += &format!(
            "#[allow(unused_imports)]\npub use super::{}::*;\n",
            module_name(m)
        );
    }
    for s in &module.structs {
        out+=&format!("#[allow(non_camel_case_types, non_snake_case)]\n#[derive(Clone, Default)]\npub struct {} {{\n",ident(&s.name));
        for (n, t) in &s.fields {
            out += &format!("pub {}: {},\n", ident(n), ty(t));
        }
        out += "}\n";
    }
    if module.palette {
        let p = palette(module)?;
        out+=&format!("pub const PALETTE_CHECKSUM: i32 = {};\npub static PALETTE: &[tg_ui::style::PaletteColor] = &[\n",p.checksum);
        for c in &p.colors {
            out += &format!(
                "tg_ui::style::PaletteColor {{ name: {:?}, rgba: {:?}, fallback: {} }},\n",
                c.name, c.rgba, c.fallback
            );
        }
        out += "];\n";
        let pairs: Vec<_> = [
            ("dialogsMenuIconFg", "dialogsBg"),
            ("windowBoldFg", "windowBg"),
        ]
        .iter()
        .filter_map(|(a, b)| {
            Some((
                p.colors.iter().position(|c| c.name == *a)?,
                p.colors.iter().position(|c| c.name == *b)?,
            ))
        })
        .collect();
        out += &format!("pub static CONTRAST_PAIRS: &[(usize,usize)] = &{pairs:?};\n");
        for c in &p.colors {
            out+=&format!("#[allow(non_snake_case)]\npub fn {}() -> tg_ui::style::Color {{ tg_ui::style::Color::palette({}) }}\n",ident(&c.name),c.index);
        }
    } else {
        for v in &module.variables {
            out += &format!(
                "#[allow(non_snake_case)]\npub fn {}() -> {} {{ {} }}\n",
                ident(&v.name),
                ty(&v.value.ty),
                named_expression(&v.value, &v.name)?
            );
        }
    }
    Ok(out)
}
fn expression(v: &Value) -> Result<String> {
    if !v.copy_of.is_empty() {
        let mut parts = v.copy_of.split('.');
        let mut out = format!("{}()", ident(parts.next().unwrap()));
        for field in parts {
            out += &format!(".{}", ident(field));
        }
        return Ok(out);
    }
    Ok(match &v.data {
        Data::Default => "Default::default()".into(),
        Data::Number(n) => {
            if v.ty == Type::Double {
                format!("{n:?}f64")
            } else {
                if v.ty == Type::Pixels {
                    format!("tg_ui::style::convert_scale({}i32)", *n as i32)
                } else {
                    format!("{}i32", *n as i32)
                }
            }
        }
        Data::Bool(b) => b.to_string(),
        Data::Text(s) => {
            if v.ty == Type::Align {
                format!("tg_ui::style::Align::named({s:?})")
            } else {
                format!("String::from({s:?})")
            }
        }
        Data::Color { rgba, .. } => match *rgba {
            [0, 0, 0, 255] => "tg_ui::style::Color::named(\"windowFg\")".into(),
            [255, 255, 255, 0] => "tg_ui::style::Color::palette(0)".into(),
            _ => format!("tg_ui::style::Color::rgba({rgba:?})"),
        },
        Data::Tuple(p) => format!(
            "{}::new({})",
            ty(&v.ty),
            p.iter()
                .map(|n| format!("tg_ui::style::convert_scale({n})"))
                .collect::<Vec<_>>()
                .join(",")
        ),
        Data::Font {
            family,
            size,
            flags,
        } => format!(
            "tg_ui::style::Font::new({family:?}, tg_ui::style::convert_scale({size}), {flags})"
        ),
        Data::Struct(fields) => {
            if fields.is_empty() {
                return Ok("Default::default()".into());
            }
            let mut s = format!("{} {{", ty(&v.ty));
            for f in fields {
                s += &format!("{}: {},", ident(&f.name), expression(&f.value)?);
            }
            s + "}"
        }
        Data::Icon(parts) => {
            let mut s = String::from("tg_ui::style::Icon::from_sources(vec![");
            for part in parts {
                let mut asset = Vec::new();
                let mut asset2 = Vec::new();
                let mut asset3 = Vec::new();
                let mut format = "size";
                let mut modifiers = Vec::new();
                let mut size = [0, 0];
                if let Some(rect) = part.filename.strip_prefix("size://") {
                    if let Some((w, h)) = rect.split_once(',') {
                        size = [w.parse().unwrap(), h.parse().unwrap()];
                        if size[0] <= 0 || size[1] <= 0 {
                            return Err(Error::new(&part.filename, 0, 103, "bad dimensions"));
                        }
                    }
                } else {
                    let path = std::path::Path::new(&part.filename);
                    let filename = path.file_name().unwrap().to_str().unwrap();
                    let mut p = filename.split('-');
                    let base = path.parent().unwrap().join(p.next().unwrap());
                    let base = base.display().to_string();
                    modifiers.extend(p.map(str::to_owned));
                    let png = format!("{base}.png");
                    let svg = format!("{base}.svg");
                    let (path, kind) = if std::path::Path::new(&svg).is_file() {
                        (svg, "svg")
                    } else {
                        (png, "png")
                    };
                    format = kind;
                    if kind == "png" {
                        for (suffix, target) in [("@2x", &mut asset2), ("@3x", &mut asset3)] {
                            let path = format!("{base}{suffix}.png");
                            *target = std::fs::read(&path).map_err(|_| {
                                Error::new(path, 0, 103, "could not open icon file")
                            })?;
                        }
                    } else if modifiers.iter().any(|m| {
                        matches!(
                            m.as_str(),
                            "invert"
                                | "flip_horizontal"
                                | "flip_vertical"
                                | "rotate_cw"
                                | "rotate_ccw"
                        )
                    }) {
                        return Err(Error::new(
                            &part.filename,
                            0,
                            666,
                            "modifiers not supported for svg yet",
                        ));
                    }
                    asset = std::fs::read(&path)
                        .map_err(|_| Error::new(path, 0, 101, "could not open icon file"))?;
                }
                s+=&format!("tg_ui::style::IconSource {{ bytes: &{asset:?}, bytes_2x: &{asset2:?}, bytes_3x: &{asset3:?}, format: {format:?}, modifiers: vec![{}], color: {}, padding: [{}], size: {:?} }},",modifiers.iter().map(|m|format!("{m:?}")).collect::<Vec<_>>().join(","),expression(&part.color)?,part.padding.iter().map(|n|format!("tg_ui::style::convert_scale({n})")).collect::<Vec<_>>().join(","),size);
            }
            s + "])"
        }
    })
}

// AyuGram: preserve the getWideMultiplied policy of the fork's generator.
fn named_expression(value: &Value, name: &str) -> Result<String> {
    let factor = match name {
        "msgMaxWidth"
        | "historyGroupWidthMax"
        | "msgServicePhotoWidth"
        | "maxMediaSize"
        | "maxWallPaperWidth"
        | "maxWallPaperHeight" => Some(1.0),
        "maxGifSize" | "maxStickerSize" | "maxAnimatedEmojiSize" => Some(0.6),
        "maxVideoMessageSize" => Some(0.75),
        _ => None,
    };
    if value.copy_of.is_empty() {
        if let Some(factor) = factor {
            if value.ty == Type::Pixels {
                return Ok(format!(
                    "tg_ui::style::wide_multiplied({}, {factor:?})",
                    expression(value)?
                ));
            }
            if let Data::Tuple(parts) = &value.data {
                if value.ty == Type::Size {
                    return Ok(format!("tg_ui::style::Size::new(tg_ui::style::wide_multiplied(tg_ui::style::convert_scale({}), {factor:?}), tg_ui::style::wide_multiplied(tg_ui::style::convert_scale({}), {factor:?}))",parts[0],parts[1]));
                }
            }
        }
    }
    expression(value)
}
