use super::parsed_file::{LangPack, PLURAL_TAGS};
use crate::common::{Error, Result};
use std::collections::BTreeMap;
#[derive(Clone, Debug)]
pub struct Generated {
    pub rust: String,
    pub indices: String,
    pub tags: String,
    pub keys_count: usize,
}
/// Explicit previous .indices/.tags data makes build state reproducible.
pub fn generate(pack: &LangPack, previous_indices: &str, file: &str) -> Result<Generated> {
    let mut known = BTreeMap::<String, (usize, usize)>::new();
    let mut next = 0;
    for line in previous_indices.lines() {
        let p: Vec<_> = line.split('\t').collect();
        if p.len() != 3 {
            continue;
        }
        if let (Ok(start), Ok(size)) = (p[1].parse::<usize>(), p[2].parse::<usize>()) {
            if size > 0 {
                known.entry(p[0].into()).or_insert((start, size));
                next = next.max(start.saturating_add(size));
            }
        }
    }
    let mut indices = vec![0; pack.entries.len()];
    for (i, e) in pack.entries.iter().enumerate() {
        let plural = !e.key_base.is_empty();
        if plural && !e.key.ends_with("__plural0") {
            continue;
        }
        let name = if plural { &e.key_base } else { &e.key };
        let size = if plural { 6 } else { 1 };
        let start = match known.get(name) {
            Some(&(start, n)) if n == size => start,
            _ => {
                let start = next;
                known.insert(name.clone(), (start, size));
                next += size;
                start
            }
        };
        for shift in 0..size {
            indices[i + shift] = start + shift;
        }
    }
    if next > 65535 {
        return Err(Error::new(format!("{file}.indices"),0,841,format!("the key table needs {next} slots, the limit is 65535. Removed keys keep their slot so that re-adding one is free; delete this file to renumber the keys from scratch.")));
    }
    if pack.tags.len() > 65535 {
        return Err(Error::new(format!("{file}.tags"),0,842,format!("there are {} tags, the limit is 65535. Delete this file to drop the tags that are not used anymore.",pack.tags.len())));
    }
    let mut out = String::from(
        "// Generated by tg-codegen. Do not edit.\nuse tg_core::lang::{Entry, Phrase};\n",
    );
    out += &format!(
        "pub const KEY_COUNT: usize = {next};\npub static TAGS: &[&str] = &{:?};\n",
        pack.tags
    );
    out += "pub static ENTRIES: &[Entry] = &[\n";
    for (i, e) in pack.entries.iter().enumerate() {
        let tags: Vec<_> = e
            .tags
            .iter()
            .map(|t| pack.tags.iter().position(|x| x == t).unwrap() as u16)
            .collect();
        out += &format!(
            "Entry {{ key: {:?}, index: {}, value: &{:?}, tags: &{:?}, plural_base: {:?} }},\n",
            e.key, indices[i], e.value, tags, e.key_base
        );
    }
    out += "];\n";
    // `lt_*` tag constants, the same names as in the original.
    for (index, tag) in pack.tags.iter().enumerate() {
        out += &format!("pub const lt_{}: u16 = {index};\n", tag_ident(tag));
    }
    // `tr::lng_*` phrases.
    out += "pub mod phrases {\nuse super::Phrase;\n";
    for (i, e) in pack.entries.iter().enumerate() {
        if !e.key_base.is_empty() && !e.key.ends_with("__plural0") {
            continue;
        }
        let name = if e.key_base.is_empty() {
            &e.key
        } else {
            &e.key_base
        };
        let tags: Vec<_> = e
            .tags
            .iter()
            .map(|t| pack.tags.iter().position(|x| x == t).unwrap() as u16)
            .collect();
        out += &format!(
            "pub const {}: Phrase = Phrase::new({}, &{:?}, {});\n",
            ident(name),
            indices[i],
            tags,
            !e.key_base.is_empty()
        );
    }
    out += "}\n";
    // Plural display modes retain C++ tag constants: count + 1000 / + 2000.
    if let Some(index) = pack.tags.iter().position(|x| x == "count") {
        out += &format!(
            "pub const COUNT_MODES: [u16;3] = [{index}, {}, {}];\n",
            index + 1000,
            index + 2000
        );
    }
    // The aliases count_short/count_decimal use the same plural base index.
    for t in PLURAL_TAGS {
        out += &format!(
            "pub const TAG_{}: Option<usize> = {:?};\n",
            t.to_ascii_uppercase(),
            pack.tags.iter().position(|x| x == t)
        );
    }
    Ok(Generated {
        rust: out,
        indices: known
            .iter()
            .map(|(n, (s, z))| format!("{n}\t{s}\t{z}\n"))
            .collect(),
        tags: pack.tags.iter().map(|s| format!("{s}\n")).collect(),
        keys_count: next,
    })
}
fn ident(s: &str) -> String {
    let mut out = String::new();
    for c in s.chars() {
        if c.is_ascii_alphanumeric() || c == '_' {
            out.push(c);
        } else {
            out += &format!("_{:x}_", c as u32);
        }
    }
    out
}
fn tag_ident(s: &str) -> String {
    ident(s)
}
