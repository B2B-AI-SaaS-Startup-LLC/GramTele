pub fn is_good_mod_exp_first(value: &BigNum, prime: &BigNum) -> bool {
    let diff = BigNum::sub(prime, value);
    !value.failed()
        && !prime.failed()
        && !diff.failed()
        && !diff.is_negative()
        && diff.bits_size() >= 1984
        && value.bits_size() >= 1984
        && value.bytes_size() <= 256
}
pub fn is_prime_and_good(bytes: &[u8], g: i32) -> bool {
    if bytes == GOOD_PRIME && matches!(g, 3 | 4 | 5 | 7) {
        return true;
    }
    let p = BigNum::from_bytes(bytes);
    if p.failed() || p.is_negative() || p.bits_size() != 2048 || !p.is_prime() {
        return false;
    }
    let good = match g {
        2 => p.count_mod_word(8) == 7,
        3 => p.count_mod_word(3) == 2,
        4 => true,
        5 => matches!(p.count_mod_word(5), 1 | 4),
        6 => matches!(p.count_mod_word(24), 19 | 23),
        7 => matches!(p.count_mod_word(7), 3 | 5 | 6),
        _ => false,
    };
    good && p.clone().sub_word(1).div_word(2, None).is_prime()
}
pub struct ModExpFirst {
    pub modexp: Vec<u8>,
    pub random_power: [u8; 256],
}
pub fn create_mod_exp(
    g: i32,
    prime_bytes: &[u8],
    seed: &[u8; 256],
    random: &mut impl Random,
) -> ModExpFirst {
    let prime = BigNum::from_bytes(prime_bytes);
    loop {
        let mut power = [0; 256];
        random.fill(&mut power);
        for (a, b) in power.iter_mut().zip(seed) {
            *a ^= *b;
        }
        let value = BigNum::mod_exp(
            &BigNum::from_word(g as u32),
            &BigNum::from_bytes(&power),
            &prime,
        );
        if is_good_mod_exp_first(&value, &prime) {
            return ModExpFirst {
                modexp: value.get_bytes(),
                random_power: power,
            };
        }
    }
}
pub fn create_auth_key(first: &[u8], power: &[u8], prime: &[u8]) -> Option<Vec<u8>> {
    let value = BigNum::from_bytes(first);
    let prime = BigNum::from_bytes(prime);
    if !is_good_mod_exp_first(&value, &prime) {
        return None;
    }
    let key = BigNum::mod_exp(&value, &BigNum::from_bytes(power), &prime);
    (!key.failed()).then(|| key.get_bytes())
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn prime_and_bounds() {
        assert!(is_prime_and_good(&GOOD_PRIME, 3));
        assert!(!is_prime_and_good(&GOOD_PRIME, 8));
        let p = BigNum::from_bytes(&GOOD_PRIME);
        assert!(!is_good_mod_exp_first(&BigNum::from_word(1), &p));
        assert!(!is_good_mod_exp_first(&p, &p));
        let mut power = [0; 256];
        power[0] = 0x80;
        let v = BigNum::mod_exp(&BigNum::from_word(3), &BigNum::from_bytes(&power), &p);
        assert!(is_good_mod_exp_first(&v, &p));
        assert!(create_auth_key(&v.get_bytes(), &power, &GOOD_PRIME).is_some());
    }
}
