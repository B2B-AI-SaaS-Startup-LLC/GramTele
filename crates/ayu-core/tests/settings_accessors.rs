use ayu_core::ayu_settings::*;
use serde_json::{json, Value};
trait NativeValue {
    fn native(self) -> Value;
}
macro_rules! numeric{($($t:ty),*)=>{$(impl NativeValue for $t{fn native(self)->Value{json!(self)}})*}}
numeric!(bool, i32, u32, u64, f64, String);
macro_rules! enums{($($t:ty),*)=>{$(impl NativeValue for $t{fn native(self)->Value{json!(self as i32)}})*}}
enums!(
    PeerIdDisplay,
    ChannelBottomButton,
    ContextMenuVisibility,
    SendWithoutSoundOption
);
impl NativeValue for TranslationProvider {
    fn native(self) -> Value {
        json!(match self {
            Self::Telegram => "telegram",
            Self::Google => "google",
            Self::Yandex => "yandex",
            Self::Native => "native",
        })
    }
}
fn check<T: NativeValue + Clone + 'static>(
    value: T,
    producer: tg_rpl::Producer<T>,
    expected: &Value,
) {
    assert_eq!(value.native(), *expected);
    let seen = std::rc::Rc::new(std::cell::RefCell::new(vec![]));
    let out = seen.clone();
    let life = tg_rpl::Lifetime::new();
    producer.on_next(move |v| out.borrow_mut().push(v.native()), &life);
    assert_eq!(*seen.borrow(), vec![expected.clone()]);
}

macro_rules! one {($changed:expr,$expected:expr,$key:literal,$get:ident,$value:ident,$changes:ident,$set:ident,$group:ident)=>{{
 check($changed.$get(),$changed.$value(),&$expected[$key]);
 let mut s=AyuSettings::default();let output=std::rc::Rc::new(std::cell::RefCell::new(vec![]));let copy=output.clone();let life=tg_rpl::Lifetime::new();
 one!(@subscribe s,$group,$changes,copy,life);
 one!(@set s,$group,$set,$changed.$get());
 assert_eq!(*output.borrow(),vec![$expected[$key].clone()]);
 one!(@set s,$group,$set,$changed.$get());assert_eq!(output.borrow().len(),1);
}};
(@subscribe $s:ident,root,$changes:ident,$out:ident,$life:ident)=>{$s.$changes().on_next(move|v|$out.borrow_mut().push(v.native()),&$life);};
(@subscribe $s:ident,ghost,$changes:ident,$out:ident,$life:ident)=>{$s.ghost(0).$changes().on_next(move|v|$out.borrow_mut().push(v.native()),&$life);};
(@set $s:ident,root,$set:ident,$value:expr)=>{$s.$set($value).unwrap();};
(@set $s:ident,ghost,$set:ident,$value:expr)=>{$s.$set(0,$value).unwrap();};
}
